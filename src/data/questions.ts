function fromSpec(s: Spec, kind: Question["kind"]): Question {
  const [id, dimension, scene, context, text, left, right, leftWhy, rightWhy] =
    s;
  return {
    id,
    kind,
    dimension,
    scene,
    context,
    npc: people[scene],
    text,
    options: [
      { id: "a", text: left, score: 1, explanation: leftWhy },
      { id: "b", text: right, score: -1, explanation: rightWhy },
      ...NEUTRAL_OPTIONS,
    ],
    eventId: id,
    weight: kind === "base" ? 1 : 0.8,
    target: {
      EI: "互动与独处时的自然精力偏好",
      SN: "获取和理解信息的自然方式",
      TF: "取舍时首先关注的判断依据",
      JP: "面对安排与变化的自然偏好",
      AT: "失误、反馈与压力后的自我体验",
    }[dimension],
    rationale: "只把选项表达的自然偏好作为线索，不推断能力、道德或职业适配。",
    crossChecks: [],
  };
}
